package server

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"testing"
)

var updateRoutes = flag.Bool("update-routes", false, "rewrite docs/reference/routes.md from the handlers")

// routesDoc is the generated route reference, relative to this package.
const routesDoc = "../../docs/reference/routes.md"

type routeDoc struct {
	method, path, handler, summary, file string
}

// TestRouteReference keeps docs/reference/routes.md in step with the
// routes the server registers. It reads every mux registration in this
// package's source, names the handler, and takes the first sentence of its
// doc comment. Run `go test ./internal/server -run TestRouteReference
// -update-routes` after adding a route.
func TestRouteReference(t *testing.T) {
	fset := token.NewFileSet()
	files, err := filepath.Glob("*.go")
	if err != nil {
		t.Fatal(err)
	}
	docs := map[string]string{}
	var parsed []*ast.File
	var names []string
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") {
			continue
		}
		af, err := parser.ParseFile(fset, f, nil, parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		parsed = append(parsed, af)
		names = append(names, f)
		for _, d := range af.Decls {
			if fd, ok := d.(*ast.FuncDecl); ok && fd.Doc != nil {
				docs[fd.Name.Name] = firstSentence(fd.Doc.Text())
			}
		}
	}
	var routes []routeDoc
	for i, af := range parsed {
		ast.Inspect(af, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok || len(call.Args) != 2 || !isRegistration(call.Fun) {
				return true
			}
			lit, ok := call.Args[0].(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				return true
			}
			pattern, _ := strconv.Unquote(lit.Value)
			method, path, found := strings.Cut(pattern, " ")
			if !found {
				method, path = "ANY", pattern
			}
			if !strings.HasPrefix(path, "/") {
				return true
			}
			h := handlerName(call.Args[1])
			if docs[h] == "" && h != "redirect" && h != "inline" {
				t.Errorf("%s: handler %s for %q has no doc comment", names[i], h, pattern)
			}
			routes = append(routes, routeDoc{method, path, types.ExprString(call.Args[1]), docs[h], names[i]})
			return true
		})
	}
	if len(routes) < 50 {
		t.Fatalf("found only %d routes; did registration change shape?", len(routes))
	}
	sort.SliceStable(routes, func(i, j int) bool {
		if routes[i].path != routes[j].path {
			return routes[i].path < routes[j].path
		}
		return routes[i].method < routes[j].method
	})
	got := renderRoutes(routes)
	if *updateRoutes {
		if err := os.MkdirAll(filepath.Dir(routesDoc), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(routesDoc, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(routesDoc)
	if err != nil || !bytes.Equal(got, want) {
		t.Fatalf("docs/reference/routes.md is out of date; run: go test ./internal/server -run TestRouteReference -update-routes")
	}
}

// isRegistration matches mux.Handle, mux.HandleFunc and the admin h helper.
func isRegistration(fun ast.Expr) bool {
	switch f := fun.(type) {
	case *ast.SelectorExpr:
		return f.Sel.Name == "Handle" || f.Sel.Name == "HandleFunc"
	case *ast.Ident:
		return f.Name == "h"
	}
	return false
}

// handlerName names the method that serves a route: s.listOrgs gives
// listOrgs, s.model(...) gives model, auth(s.login) gives login.
func handlerName(e ast.Expr) string {
	switch v := e.(type) {
	case *ast.SelectorExpr:
		return v.Sel.Name
	case *ast.Ident:
		return v.Name
	case *ast.CallExpr:
		if _, ok := v.Fun.(*ast.Ident); ok && len(v.Args) == 1 {
			return handlerName(v.Args[0]) // a wrapper such as auth(...)
		}
		if sel, ok := v.Fun.(*ast.SelectorExpr); ok {
			if sel.Sel.Name == "RedirectHandler" || sel.Sel.Name == "HandlerFunc" {
				return "redirect"
			}
			return sel.Sel.Name
		}
	case *ast.FuncLit:
		return "inline"
	}
	return "?"
}

func firstSentence(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if i := strings.Index(s, ". "); i >= 0 {
		s = s[:i+1]
	}
	return s
}

func renderRoutes(routes []routeDoc) []byte {
	var b bytes.Buffer
	b.WriteString("# Route reference\n\n")
	b.WriteString("<!-- Generated by `go test ./internal/server -run TestRouteReference -update-routes`; do not edit. -->\n\n")
	b.WriteString("Every route the gateway serves, generated from the handlers in `internal/server`. ")
	b.WriteString("Contracts, errors and headers are described in the [API specification](../api.md); ")
	b.WriteString("this page is the complete list, so a route missing here does not exist.\n")
	groups := []struct{ title, prefix string }{
		{"Model API", "/v1"},
		{"MCP gateway", "/mcp"},
		{"Admin API", "/admin/"},
		{"Admin UI and sign-in", "/ui"},
		{"Discovery and operations", ""},
	}
	used := make([]bool, len(routes))
	for _, g := range groups {
		var rows []string
		for i, r := range routes {
			if used[i] {
				continue
			}
			if g.prefix != "" && !strings.HasPrefix(r.path, g.prefix) {
				continue
			}
			used[i] = true
			summary := r.summary
			if summary == "" {
				summary = "-"
			}
			rows = append(rows, fmt.Sprintf("| `%s` | `%s` | `%s` | %s |", r.method, r.path, r.handler, strings.ReplaceAll(summary, "|", "\\|")))
		}
		if len(rows) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n## %s\n\n| Method | Path | Handler | Summary |\n| --- | --- | --- | --- |\n", g.title)
		b.WriteString(strings.Join(rows, "\n"))
		b.WriteString("\n")
	}
	return b.Bytes()
}
